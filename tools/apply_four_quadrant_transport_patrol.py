def balanced_end(text: str, start: int, opener: str, closer: str, label: str) -> int:
    depth = 0
    quoted = False
    escaped = False
    for index in range(start, len(text)):
        char = text[index]
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
            continue
        if char == '"':
            quoted = True
        elif char == opener:
            depth += 1
        elif char == closer:
            depth -= 1
            if depth == 0:
                return index + 1
    raise PatchError(f"Unbalanced block: {label}")


def marked_bounds(text: str, begin: str, end: str) -> tuple[int, int] | None:
    begin_at = text.find(begin)
    if begin_at < 0:
        return None
    end_at = text.find(end, begin_at)
    if end_at < 0:
        raise PatchError(f"Existing section {begin} has no end marker")
    start = text.rfind("\n", 0, begin_at) + 1
    finish = text.find("\n", end_at)
    finish = len(text) if finish < 0 else finish + 1
    return start, finish


def strip_marked(text: str, begin: str, end: str) -> str:
    bounds = marked_bounds(text, begin, end)
    if not bounds:
        return text
    return text[: bounds[0]] + text[bounds[1] :]


def upsert_before(text: str, begin: str, end: str, section: str, anchor: str) -> str:
    rendered = section.rstrip() + "\n"
    bounds = marked_bounds(text, begin, end)
    if bounds:
        return text[: bounds[0]] + rendered + text[bounds[1] :]
    anchor_at = text.find(anchor)
    if anchor_at < 0:
        raise PatchError(f"Missing insertion anchor for {begin}: {anchor}")
    line_start = text.rfind("\n", 0, anchor_at) + 1
    return text[:line_start] + rendered + "\n" + text[line_start:]


def remove_trigger(text: str, name: str) -> str:
    marker = f'{{"{name}"'
    start = text.find(marker)
    if start < 0:
        return text
    block_start = start
    while block_start > 0 and text[block_start - 1] in "\t ":
        block_start -= 1
    end = balanced_end(text, start, "{", "}", name)
    while end < len(text) and text[end] in "\r\n":
        end += 1
    return text[:block_start] + text[end:]


def idempotent_replace(text: str, old: str, new: str, label: str) -> str:
    old_count = text.count(old)
    new_count = text.count(new)
    if old_count == 1 and new_count == 0:
        return text.replace(old, new, 1)
    if old_count == 0 and new_count == 1:
        return text
    raise PatchError(
        f"{label}: expected one original or one patched occurrence; "
        f"found old={old_count}, new={new_count}"
    )


def extract_entity(text: str, entity_id: int) -> str:
    token = f"0x{entity_id:x}"
    match = re.search(r'\{(?:Entity|Human)\s+"[^"]+"\s+' + re.escape(token) + r'\b', text)
    if not match:
        raise PatchError(f"Missing source motor entity {token}")
    end = balanced_end(text, match.start(), "{", "}", token)
    return text[match.start() : end]


def render_enemy_packages(text: str) -> str:
    blocks: list[str] = [PACKAGE_BEGIN]
    links: list[str] = []
    tags: list[str] = [TAG_BEGIN]

    for faction, cfg in FACTIONS.items():
        source_start = int(cfg["source_start"])
        enemy_start = int(cfg["enemy_start"])
        enemy_mid = int(cfg["enemy_mid"])
        id_map = {
            source_start + offset: enemy_start + offset for offset in range(11)
        }
        blocks.append(f"; ----- ENEMY NORMAL {faction.upper()} TRANSPORT -----")
        for offset in range(11):
            source_id = source_start + offset
            block = extract_entity(text, source_id)
            for old_id, new_id in id_map.items():
                block = re.sub(
                    rf"\b0x{old_id:x}\b", f"0x{new_id:x}", block, flags=re.IGNORECASE
                )
            block = re.sub(
                r"\{MID\s+\d+\}", f"{{MID {enemy_mid + offset}}}", block, count=1
            )
            blocks.append(block)

        hull = enemy_start
        links.append(f'\t{{Link 0x{hull + 1:x} {{0x{hull:x} "driver"}}}}')
        links.append(f'\t{{Link 0x{hull + 2:x} {{0x{hull:x} "commander"}}}}')
        for seat in range(1, 9):
            links.append(
                f'\t{{Link 0x{hull + 2 + seat:x} {{0x{hull:x} "seat{seat}"}}}}'
            )

        package = f"transport_enemy_{faction}"
        for offset in range(11):
            entity = enemy_start + offset
            role = (
                f"{package}_hull"
                if offset == 0
                else (f"{package}_crew" if offset <= 2 else f"{package}_pax")
            )
            tags.append(
                f'\t{{Tags "transport_enemy_tpl" "{package}" "{role}" "hidden" 0x{entity:x}}}'
            )

    blocks.extend(links)
    blocks.append(PACKAGE_END)
    tags.append(TAG_END)
    return "\n".join(blocks), "\n".join(tags)


def patch_templates(text: str) -> str:
    for begin, end in OLD_MARKER_PAIRS[:2]:
        text = strip_marked(text, begin, end)
    packages, tags = render_enemy_packages(text)
    text = upsert_before(
        text,
        PACKAGE_BEGIN,
        PACKAGE_END,
        packages,
        "; ===== E2 AIR PACKAGE POOLS",
    )
    return upsert_before(
        text,
        TAG_BEGIN,
        TAG_END,
        tags,
        '\t{Tags "ally_sup_tpl" "support_e2_tpl"',
    )


