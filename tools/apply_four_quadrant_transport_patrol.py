def render_engine(engine: Engine) -> str:
    begin = ENGINE_BEGIN.format(key=engine.key.upper())
    end = ENGINE_END.format(key=engine.key.upper())
    parts = [
        begin,
        "\t\t\t; Ordinary combat transport: no timed emit, turnaround, withdrawal,",
        "\t\t\t; deletion, or cleanup. Route targets flag-perimeter waypoints only.",
        render_place(engine),
        render_issue_patrol(engine),
    ]
    parts.extend(render_dispatch(engine, faction) for faction in FACTIONS)
    parts.extend((render_patrol_trigger(engine), end))
    return "\n\n".join(parts)


def patch_engine(text: str, engine: Engine) -> str:
    # Remove superseded two-truck controls if this overlay is applied without the
    # baseline wrapper first.
    for begin, end in OLD_MARKER_PAIRS[2:]:
        text = strip_marked(text, begin, end)

    # Disable every timer-driven motor dispatch. Helper macros remain harmless and
    # are useful historical reference, but no old motor trigger has a live budget.
    if engine.key == "as":
        text = remove_trigger(text, "attack_support/motor_test")
        text = idempotent_replace(
            text,
            '{"set_i" {var "attack_support_motor_left$"} {op "="} {value 1}}',
            '{"set_i" {var "attack_support_motor_left$"} {op "="} {value 0}}',
            "friendly attacker scripted motor budget",
        )
        text = idempotent_replace(
            text,
            '{"set_i" {var "attack_support_motor_test$"} {op "="} {value 1}}',
            '{"set_i" {var "attack_support_motor_test$"} {op "="} {value 0}}',
            "friendly attacker forced motor mode",
        )
    elif engine.key == "ds":
        text = remove_trigger(text, "defense_support/motor_test")
    elif engine.key == "ea":
        text = remove_trigger(text, "enemy_attack/motor_test")
        text = idempotent_replace(
            text,
            '{"set_i" {var "enemy_attack_motor_left$"} {op "="} {value 1}}',
            '{"set_i" {var "enemy_attack_motor_left$"} {op "="} {value 0}}',
            "enemy attacker scripted motor budget",
        )
        text = idempotent_replace(
            text,
            '{"set_i" {var "enemy_attack_motor_test$"} {op "="} {value 1}}',
            '{"set_i" {var "enemy_attack_motor_test$"} {op "="} {value 0}}',
            "enemy attacker forced motor mode",
        )

    begin = ENGINE_BEGIN.format(key=engine.key.upper())
    end = ENGINE_END.format(key=engine.key.upper())
    return upsert_before(text, begin, end, render_engine(engine), engine.anchor)


def patch_vars(text: str) -> str:
    # Remove the superseded comparison-only vars when present.
    text = re.sub(r'^[ \t]*\{"motor_compare_(?:friend|enemy)_done"\}\r?\n', '', text, flags=re.MULTILINE)
    vars_lines = [VARS_BEGIN]
    for engine in ENGINES:
        vars_lines.append(f'\t\t\t{{"{engine.done_var}"}}')
        vars_lines.append(f'\t\t\t{{"{engine.step_var}"}}')
    vars_lines.append(VARS_END)
    section = "\n".join(vars_lines)
    bounds = marked_bounds(text, VARS_BEGIN, VARS_END)
    if bounds:
        return text[: bounds[0]] + section + "\n" + text[bounds[1] :]
    anchor = '\t\t\t{"enemy_attack_motor_test_done"}'
    if text.count(anchor) != 1:
        raise PatchError("dcg_vars transport insertion anchor is not unique")
    return text.replace(anchor, anchor + "\n" + section, 1)


def read_text(path: Path) -> tuple[str, bool]:
    raw = path.read_bytes()
    return raw.decode("utf-8-sig"), raw.startswith(b"\xef\xbb\xbf")


def write_text(path: Path, text: str, bom: bool) -> None:
    raw = text.encode("utf-8")
    path.write_bytes((b"\xef\xbb\xbf" if bom else b"") + raw)


def validate_engine(text: str, engine: Engine) -> None:
    begin = ENGINE_BEGIN.format(key=engine.key.upper())
    end = ENGINE_END.format(key=engine.key.upper())
    bounds = marked_bounds(text, begin, end)
    if not bounds:
        raise PatchError(f"Missing transport section for {engine.key}")
    block = text[bounds[0] : bounds[1]]

    for faction in FACTIONS:
        trigger = f'{{"{engine.trigger_ns}/normal_transport_{faction}"'
        if block.count(trigger) != 1:
            raise PatchError(f"{engine.key}: missing or duplicate {faction} dispatch")
    if block.count(f'{{"{engine.trigger_ns}/normal_transport_patrol"') != 1:
        raise PatchError(f"{engine.key}: patrol trigger missing or duplicated")
    for step in range(1, 6):
        if f'{{waypoint "transport_patrol_flag_{step}"}}' not in block:
            raise PatchError(f"{engine.key}: route waypoint {step} is missing")
    for token in (
        '{action move}',
        '{distance 80}',
        f'{{tag {engine.hull_tag}}}',
        f'{{tag {engine.pax_tag}}}',
        f'("{engine.owner_macro}")',
        '{"delay" {time 45}}',
    ):
        if token not in block:
            raise PatchError(f"{engine.key}: normal transport section missing {token}")
    for forbidden in (
        '{"emit"',
        '{mode passengers}',
        'exit_motor_to_origin',
        'motor_leaving',
        '{"delete"',
        '{"delay" {time 75}}',
    ):
        if forbidden in block:
            raise PatchError(f"{engine.key}: normal transport contains {forbidden}")


def validate(root: Path) -> None:
    multi = root / "resource/map/multi"
    templates = (multi / "faction_support_templates.inc").read_text(encoding="utf-8-sig")
    variables = (multi / "dcg_vars.inc").read_text(encoding="utf-8-sig")

    for marker in (PACKAGE_BEGIN, PACKAGE_END, TAG_BEGIN, TAG_END):
        if templates.count(marker) != 1:
            raise PatchError(f"Template marker count invalid: {marker}")
    for faction, cfg in FACTIONS.items():
        start = int(cfg["enemy_start"])
        if templates.count(f"0x{start:x}") < 2:
            raise PatchError(f"Enemy {faction} transport hull or link is missing")
        for seat in range(1, 9):
            if f'{{0x{start:x} "seat{seat}"}}' not in templates:
                raise PatchError(f"Enemy {faction} seat{seat} link is missing")
        package = f"transport_enemy_{faction}"
        if templates.count(f'"{package}"') < 11:
            raise PatchError(f"Enemy {faction} package tags are incomplete")

    for engine in ENGINES:
        text = (multi / engine.filename).read_text(encoding="utf-8-sig")
        validate_engine(text, engine)

    attack = (multi / "attack_support_waves.inc").read_text(encoding="utf-8-sig")
    defense = (multi / "defense_support_waves.inc").read_text(encoding="utf-8-sig")
    enemy_attack = (multi / "enemy_attack_support.inc").read_text(encoding="utf-8-sig")
    if '{"attack_support/motor_test"' in attack:
        raise PatchError("Old friendly-attacker timed motor trigger is still active")
    if '{"defense_support/motor_test"' in defense:
        raise PatchError("Old friendly-defender timed motor trigger is still active")
    if '{"enemy_attack/motor_test"' in enemy_attack:
        raise PatchError("Old enemy-attacker timed motor trigger is still active")
    for text, var in (
        (attack, "attack_support_motor_left"),
        (attack, "attack_support_motor_test"),
        (enemy_attack, "enemy_attack_motor_left"),
        (enemy_attack, "enemy_attack_motor_test"),
    ):
        token = f'{{"set_i" {{var "{var}$"}} {{op "="}} {{value 0}}}}'
        if text.count(token) != 1:
            raise PatchError(f"Scripted motor disablement missing: {var}")

    for engine in ENGINES:
        for var in (engine.done_var, engine.step_var):
            if variables.count(f'{{"{var}"}}') != 1:
                raise PatchError(f"Transport var missing or duplicated: {var}")


def apply(root: Path, *, check_only: bool = False) -> list[Path]:
    multi = root / "resource/map/multi"
    paths = {name: multi / name for name in FILES}
    for path in paths.values():
        if not path.is_file():
            raise PatchError(f"Missing required file: {path}")

    results: dict[str, tuple[str, bool]] = {}
    changed: list[Path] = []
    engine_by_file = {engine.filename: engine for engine in ENGINES}

    for name, path in paths.items():
        text, bom = read_text(path)
        if name == "faction_support_templates.inc":
            patched = patch_templates(text)
        elif name == "dcg_vars.inc":
            patched = patch_vars(text)
        else:
            patched = patch_engine(text, engine_by_file[name])
        results[name] = (patched, bom)
        if patched != text:
            changed.append(path)

    if not check_only:
        for name, (patched, bom) in results.items():
            write_text(paths[name], patched, bom)
        validate(root)
    return changed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        validate(args.root)
        print("Four-quadrant normal transport patrols validated.")
    else:
        changed = apply(args.root)
        print(f"Four-quadrant normal transport patrol patched {len(changed)} file(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
